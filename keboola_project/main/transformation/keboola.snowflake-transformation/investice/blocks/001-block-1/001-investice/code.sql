-- Jaký je zisk za cele sledované obdobi?
CREATE OR REPLACE TABLE ZISK_ODJAKZIVA AS
SELECT T1.OBDOBI,
       T1.TYP_INVESTICE,
       SUM(T2.ZISK_OPROTI_OBDOBI_PRED_MESICEM) AS ZISK_ODJAKZIVA
FROM PORTFOLIO_PART_1 T1
    LEFT JOIN PORTFOLIO_PART_1 T2
              ON T2.TYP_INVESTICE = T1.TYP_INVESTICE
                  AND T2.OBDOBI <= T1.OBDOBI
GROUP BY T1.OBDOBI, T1.TYP_INVESTICE;

-- Druhá část reportu
CREATE OR REPLACE TABLE PORTFOLIO_PART_2 AS
SELECT distinct
  T1.DATUM_SNAPSHOTU,
       T1.OBDOBI,
       T1.TYP_INVESTICE,
       T1.PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM,
       T1.PRIRUSTEK_OPROTI_OBDOBI_PRED_ROKEM,
       T1.HODNOTA,
       T1.HODNOTA_V_OBDOBI_PRED_MESICEM,
       T1.HODNOTA_V_OBDOBI_PRED_ROKEM,
       T1.ZISK_OPROTI_OBDOBI_PRED_MESICEM,
       T1.ZISK_OPROTI_OBDOBI_PRED_ROKEM,
       T1.PODIL_MESICNIHO_ZISKU_OPROTI_CELKOVE_HODNOTE,
       T1.PODIL_ROCNIHO_ZISKU_OPROTI_CELKOVE_HODNOTE,
       T2.ZISK_ODJAKZIVA
FROM PORTFOLIO_PART_1 T1
    LEFT JOIN ZISK_ODJAKZIVA T2
              ON T2.OBDOBI = T1.OBDOBI
                  AND T2.TYP_INVESTICE = T1.TYP_INVESTICE;
