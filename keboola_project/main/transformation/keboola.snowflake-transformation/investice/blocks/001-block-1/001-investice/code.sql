-- Formátování
CREATE OR REPLACE TABLE DATA_INPUT AS
SELECT DATUM_SNAPSHOTU,
       OBDOBI :: NUMBER AS OBDOBI,
       TYP_INVESTICE,
       REPLACE(PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM, ',', '') :: NUMBER AS PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM,
       REPLACE(HODNOTA, ',', '') :: NUMBER AS HODNOTA
FROM DATA_INPUT;

-- Kolik jsem nainvestoval za rok?
CREATE OR REPLACE TABLE PRIRUSTEK_PRED_ROKEM AS
SELECT T1.TYP_INVESTICE,
       T1.OBDOBI,
       SUM(T2.PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM)
           AS PRIRUSTEK_OPROTI_OBDOBI_PRED_ROKEM
FROM DATA_INPUT T1
    -- Pripojeni hodnot od aktualniho obdobi po obdobi - 11
    LEFT JOIN DATA_INPUT T2
              ON T2.TYP_INVESTICE = T1.TYP_INVESTICE
                  AND T2.OBDOBI <= T1.OBDOBI
                  AND T2.OBDOBI >= (T1.OBDOBI - 11)
GROUP BY T1.TYP_INVESTICE, T1.OBDOBI;

-- Jaká byla úvodní hodnota investic?
CREATE OR REPLACE TABLE HODNOTA_PRVNI_OBDOBI AS
SELECT TYP_INVESTICE,
       IFNULL(HODNOTA, 0) :: NUMBER AS HODNOTA_V_PRVNIM_OBDOBI
FROM DATA_INPUT
WHERE OBDOBI = 0;

-- Jakou mělo portfolio hodnotu před měsícem?
CREATE OR REPLACE TABLE HODNOTA_PRED_MESICEM AS
SELECT T1.DATUM_SNAPSHOTU,
       T1.OBDOBI,
       T1.TYP_INVESTICE,
       COALESCE(T2.HODNOTA,
                T3.HODNOTA_V_PRVNIM_OBDOBI) :: NUMBER AS HODNOTA_V_OBDOBI_PRED_MESICEM
FROM DATA_INPUT T1
    LEFT JOIN DATA_INPUT T2
              ON T2.TYP_INVESTICE = T1.TYP_INVESTICE
                  AND T2.OBDOBI = T1.OBDOBI - 1
    LEFT JOIN HODNOTA_PRVNI_OBDOBI T3
              ON T3.TYP_INVESTICE = T1.TYP_INVESTICE;

-- Jakou mělo portfolio hodnotu před rokem?
CREATE OR REPLACE TABLE HODNOTA_PRED_ROKEM AS
SELECT T1.DATUM_SNAPSHOTU,
       T1.OBDOBI,
       T1.TYP_INVESTICE,
       IFNULL(T2.HODNOTA,
              T3.HODNOTA_V_PRVNIM_OBDOBI) :: NUMBER AS HODNOTA_V_OBDOBI_PRED_ROKEM
FROM DATA_INPUT T1
    LEFT JOIN DATA_INPUT T2
              ON T2.TYP_INVESTICE = T1.TYP_INVESTICE
                  AND T2.OBDOBI = T1.OBDOBI - 12
    LEFT JOIN HODNOTA_PRVNI_OBDOBI T3
              ON T3.TYP_INVESTICE = T1.TYP_INVESTICE;

-- První část reportu
CREATE OR REPLACE TABLE PORTFOLIO_PART_1 AS
SELECT DI.DATUM_SNAPSHOTU,
       DI.OBDOBI,
       DI.TYP_INVESTICE,
       DI.PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM,
       T1.PRIRUSTEK_OPROTI_OBDOBI_PRED_ROKEM,
       DI.HODNOTA,
       T2.HODNOTA_V_OBDOBI_PRED_MESICEM,
       T3.HODNOTA_V_OBDOBI_PRED_ROKEM,
       DI.HODNOTA
           - T2.HODNOTA_V_OBDOBI_PRED_MESICEM
           - DI.PRIRUSTEK_OPROTI_OBDOBI_PRED_MESICEM AS ZISK_OPROTI_OBDOBI_PRED_MESICEM,
       DI.HODNOTA
           - T3.HODNOTA_V_OBDOBI_PRED_ROKEM
           - T1.PRIRUSTEK_OPROTI_OBDOBI_PRED_ROKEM   AS ZISK_OPROTI_OBDOBI_PRED_ROKEM,
       ZISK_OPROTI_OBDOBI_PRED_MESICEM / HODNOTA     AS PODIL_MESICNIHO_ZISKU_OPROTI_CELKOVE_HODNOTE,
       ZISK_OPROTI_OBDOBI_PRED_ROKEM / HODNOTA       AS PODIL_ROCNIHO_ZISKU_OPROTI_CELKOVE_HODNOTE
FROM DATA_INPUT DI
    LEFT JOIN PRIRUSTEK_PRED_ROKEM T1
              ON T1.TYP_INVESTICE = DI.TYP_INVESTICE
                  AND T1.OBDOBI = DI.OBDOBI
    LEFT JOIN HODNOTA_PRED_MESICEM T2
              ON T2.TYP_INVESTICE = DI.TYP_INVESTICE
                  AND T2.OBDOBI = DI.OBDOBI
    LEFT JOIN HODNOTA_PRED_ROKEM T3
              ON T3.TYP_INVESTICE = DI.TYP_INVESTICE
                  AND T3.OBDOBI = DI.OBDOBI;

